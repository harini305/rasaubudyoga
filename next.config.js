/** @type {import('next').NextConfig} */

// Long-lived browser caching for static media (fewer repeat downloads = less Vercel bandwidth).
// Filenames aren't content-hashed, so this is 30 days rather than a year. Re-name an image if it changes.
const mediaCache = [{ key: 'Cache-Control', value: 'public, max-age=2592000, stale-while-revalidate=86400' }];

const nextConfig = {
  // Preserve the original WordPress URL shape (/about-us/, /yoga-home/ …).
  trailingSlash: true,
  // Static-only site: no server timing header noise.
  poweredByHeader: false,
  images: {
    // Built-in optimisation is disabled to avoid Vercel Image Optimization usage.
    // Responsive WebP derivatives are pre-generated by `npm run images`.
    unoptimized: true,
  },
  async headers() {
    return [
      { source: '/images/:path*', headers: mediaCache },
      { source: '/brand/:path*', headers: mediaCache },
      { source: '/og/:path*', headers: mediaCache },
    ];
  },
};

module.exports = nextConfig;
